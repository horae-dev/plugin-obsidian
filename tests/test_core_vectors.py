"""Drift guard: the writer accepts every note the core's real `note_after` makes, and its
marker recogniser finds the core's spans (`tests/data/core_note_vectors.json`, generated by
`tests/data/core_vectors.py` from the core commit named in its header)."""

import json
from pathlib import Path
from typing import Any

import pytest
from horae_sdk import SinkError

from horae_obsidian import writer

DATA = json.loads((Path(__file__).parent / "data/core_note_vectors.json").read_text("utf-8"))
VECTORS: list[dict[str, Any]] = DATA["vectors"]


def encoded(text: str | None) -> bytes | None:
    return None if text is None else text.encode("utf-8")


def test_the_vectors_name_their_core_commit() -> None:
    assert len(DATA["core_commit"]) == 40
    assert DATA["core_file"] == "src/horae/apply/notes.py"
    kinds = {vector["error"] for vector in VECTORS}
    assert kinds == {None, "block_ambiguous", "not_owned"}
    names = " ".join(vector["name"] for vector in VECTORS)
    for case in ("'\\r\\n'", "bom", "at the start", "at the end", "empty block", "upper-case"):
        assert case in names


@pytest.mark.parametrize(
    "vector", [v for v in VECTORS if v["error"] is None], ids=lambda v: v["name"]
)
def test_the_writer_accepts_what_the_core_writes(vector: dict[str, Any]) -> None:
    before, after = encoded(vector["before"]), encoded(vector["after"])
    assert after is not None
    writer.check_apply(vector["intent"], before, after)
    if before is not None:  # and `horae undo` may put the note back
        writer.check_restore(vector["intent"]["path"], after, before)


@pytest.mark.parametrize("vector", [v for v in VECTORS if "spans" in v], ids=lambda v: v["name"])
def test_block_span_agrees_with_the_core(vector: dict[str, Any]) -> None:
    block = vector["intent"]["block"]
    for side in ("before", "after"):
        text, expected = vector[side], vector["spans"][side]
        if text is None:
            continue
        if isinstance(expected, str):
            with pytest.raises(SinkError) as raised:
                writer.block_span(text, block, "p")
            assert raised.value.kind == expected
        else:
            found = writer.block_span(text, block, "p")
            assert found == (None if expected is None else tuple(expected))
